import 'package:sakani/features/apartments/domain/entities/apartment_entity.dart';

class ApartmentModel extends ApartmentEntity {
  ApartmentModel({
    required super.id,
    required super.ownerId,
    required super.ownerName,
    required super.title,
    required super.description,
    required super.city,
    required super.address,
    super.latitude = 0.0,
    super.longitude = 0.0,
    super.bedrooms = 1,
    super.bathrooms = 1,
    super.area = 0.0,
    super.amenities = const [],
    super.images = const [],
    super.availableRentTypes = const ['شهري'],
    super.dailyPrice = 0.0,
    super.monthlyPrice = 0.0,
    super.yearlyPrice = 0.0,
    super.securityDeposit = 0.0,
    super.contactPhone = '',
    super.cancellationPolicy = 'مرنة',
    super.maxGuests = 2,
    super.isAvailable = true,
    super.createdAt,
  });

  Map<String, dynamic> toMap() {
    return {
      'id': id,
      'ownerId': ownerId,
      'ownerName': ownerName,
      'title': title,
      'description': description,
      'city': city,
      'address': address,
      'latitude': latitude,
      'longitude': longitude,
      'bedrooms': bedrooms,
      'bathrooms': bathrooms,
      'area': area,
      'amenities': amenities,
      'images': images,
      'availableRentTypes': availableRentTypes,
      'dailyPrice': dailyPrice,
      'monthlyPrice': monthlyPrice,
      'yearlyPrice': yearlyPrice,
      'securityDeposit': securityDeposit,
      'contactPhone': contactPhone,
      'cancellationPolicy': cancellationPolicy,
      'maxGuests': maxGuests,
      'isAvailable': isAvailable,
      'createdAt': createdAt.toIso8601String(),
    };
  }

  factory ApartmentModel.fromMap(Map<String, dynamic> map, String id) {
    return ApartmentModel(
      id: id,
      ownerId: map['ownerId'] ?? '',
      ownerName: map['ownerName'] ?? '',
      title: map['title'] ?? '',
      description: map['description'] ?? '',
      city: map['city'] ?? '',
      address: map['address'] ?? '',
      latitude: (map['latitude'] ?? 0.0).toDouble(),
      longitude: (map['longitude'] ?? 0.0).toDouble(),
      bedrooms: map['bedrooms'] ?? 1,
      bathrooms: map['bathrooms'] ?? 1,
      area: (map['area'] ?? 0.0).toDouble(),
      amenities: List<String>.from(map['amenities'] ?? []),
      images: List<String>.from(map['images'] ?? []),
      availableRentTypes: List<String>.from(
        map['availableRentTypes'] ?? ['شهري'],
      ),
      dailyPrice: (map['dailyPrice'] ?? 0.0).toDouble(),
      monthlyPrice: (map['monthlyPrice'] ?? 0.0).toDouble(),
      yearlyPrice: (map['yearlyPrice'] ?? 0.0).toDouble(),
      securityDeposit: (map['securityDeposit'] ?? 0.0).toDouble(),
      contactPhone: map['contactPhone'] ?? '',
      maxGuests: map['maxGuests'] ?? 2,
      isAvailable: map['isAvailable'] ?? true,
      createdAt: map['createdAt'] != null
          ? DateTime.tryParse(map['createdAt']) ?? DateTime.now()
          : DateTime.now(),
    );
  }

  factory ApartmentModel.fromEntity(ApartmentEntity entity) {
    return ApartmentModel(
      id: entity.id,
      ownerId: entity.ownerId,
      ownerName: entity.ownerName,
      title: entity.title,
      description: entity.description,
      city: entity.city,
      address: entity.address,
      latitude: entity.latitude,
      longitude: entity.longitude,
      bedrooms: entity.bedrooms,
      bathrooms: entity.bathrooms,
      area: entity.area,
      amenities: entity.amenities,
      images: entity.images,
      availableRentTypes: entity.availableRentTypes,
      dailyPrice: entity.dailyPrice,
      monthlyPrice: entity.monthlyPrice,
      yearlyPrice: entity.yearlyPrice,
      securityDeposit: entity.securityDeposit,
      contactPhone: entity.contactPhone,
      cancellationPolicy: entity.cancellationPolicy,
      maxGuests: entity.maxGuests,
      isAvailable: entity.isAvailable,
      createdAt: entity.createdAt,
    );
  }

  ApartmentModel copyWith({
    String? id,
    String? ownerId,
    String? ownerName,
    String? title,
    String? description,
    String? city,
    String? address,
    double? latitude,
    double? longitude,
    int? bedrooms,
    int? bathrooms,
    double? area,
    List<String>? amenities,
    List<String>? images,
    List<String>? availableRentTypes,
    double? dailyPrice,
    double? monthlyPrice,
    double? yearlyPrice,
    double? securityDeposit,
    String? contactPhone,
    String? cancellationPolicy,
    int? maxGuests,
    bool? isAvailable,
    DateTime? createdAt,
  }) {
    return ApartmentModel(
      id: id ?? this.id,
      ownerId: ownerId ?? this.ownerId,
      ownerName: ownerName ?? this.ownerName,
      title: title ?? this.title,
      description: description ?? this.description,
      city: city ?? this.city,
      address: address ?? this.address,
      latitude: latitude ?? this.latitude,
      longitude: longitude ?? this.longitude,
      bedrooms: bedrooms ?? this.bedrooms,
      bathrooms: bathrooms ?? this.bathrooms,
      area: area ?? this.area,
      amenities: amenities ?? this.amenities,
      images: images ?? this.images,
      availableRentTypes: availableRentTypes ?? this.availableRentTypes,
      dailyPrice: dailyPrice ?? this.dailyPrice,
      monthlyPrice: monthlyPrice ?? this.monthlyPrice,
      yearlyPrice: yearlyPrice ?? this.yearlyPrice,
      securityDeposit: securityDeposit ?? this.securityDeposit,
      contactPhone: contactPhone ?? this.contactPhone,
      cancellationPolicy: cancellationPolicy ?? this.cancellationPolicy,
      maxGuests: maxGuests ?? this.maxGuests,
      isAvailable: isAvailable ?? this.isAvailable,
      createdAt: createdAt ?? this.createdAt,
    );
  }
}

/// Backwards compatibility alias
typedef Apartment = ApartmentModel;
